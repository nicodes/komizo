//go:embed runtime/helpers/*.asset runtime/helpers/*.cjs runtime/helpers/*.mjs runtime/helpers/*.mod runtime/helpers/*.py runtime/helpers/*.sh runtime/helpers/*.sum
var runtimeFiles embed.FS

func runtimeInventory() map[string]string {
	files := map[string]string{}
	_ = fs.WalkDir(runtimeFiles, "runtime", func(path string, entry fs.DirEntry, err error) error {
		if err == nil && !entry.IsDir() {
			b, _ := runtimeFiles.ReadFile(path)
			files[strings.TrimSuffix(strings.TrimPrefix(path, "runtime/"), ".asset")] = digest(b)
		}
		return err
	})
	return files
}

func RuntimeIdentity() string {
	b, _ := json.Marshal(runtimeInventory())
	return digest(b)
}

func cacheDirectory() (string, error) {
	if dir := os.Getenv("KOMIZO_CACHE_DIR"); dir != "" {
		return filepath.Abs(dir)
	}
	dir, err := os.UserCacheDir()
	return filepath.Join(dir, "komizo"), err
}

func atomicFile(path string, data []byte, mode fs.FileMode) error {
	if current, err := os.Lstat(path); err == nil && !current.Mode().IsRegular() {
		return errors.New("refusing to replace a nonregular configuration file")
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".komizo-write-*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer os.Remove(tmp)
	if err = f.Chmod(mode); err == nil {
		_, err = f.Write(data)
	}
	closeErr := f.Close()
	if err != nil {
		return err
	}
	if closeErr != nil {
		return closeErr
	}
	return os.Rename(tmp, path)
}

func verifyRuntime(root string, files map[string]string) error {
	actual := map[string]bool{}
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return errors.New("runtime cache contains a symbolic link")
		}
		if entry.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)
		if rel == "SOURCE.json" {
			b, err := os.ReadFile(path)
			expected, _ := json.MarshalIndent(map[string]any{"repository": "https://github.com/nicodes/komizo", "revision": RuntimeIdentity(), "files": files}, "", "  ")
			if err != nil || digest(b) != digest(append(expected, '\n')) {
				return errors.New("runtime source manifest differs")
			}
			actual[rel] = true
			return nil
		}
		b, err := os.ReadFile(path)
		if err != nil || digest(b) != files[rel] {
			return fmt.Errorf("runtime integrity mismatch: %s", rel)
		}
		actual[rel] = true
		return nil
	})
	if err != nil {
		return err
	}
	if len(actual) != len(files)+1 {
		return errors.New("runtime inventory is incomplete")
	}
	return nil
}

// Runtime materializes only compiled-in bytes and verifies them before each use.
func Runtime() (string, error) {
	cache, err := cacheDirectory()
	if err != nil {
		return "", err
	}
	base := filepath.Join(cache, "runtime")
	if err = os.MkdirAll(base, 0o700); err != nil {
		return "", err
	}
	files := runtimeInventory()
	root := filepath.Join(base, RuntimeIdentity())
	if _, err := os.Lstat(root); err == nil {
		return root, verifyRuntime(root, files)
	}
	tmp, err := os.MkdirTemp(base, ".runtime-*")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(tmp)
	for relative := range files {
		b, err := runtimeFiles.ReadFile("runtime/" + relative)
		if err != nil {
			b, err = runtimeFiles.ReadFile("runtime/" + relative + ".asset")
			if err != nil {
				return "", err
			}
		}
		path := filepath.Join(tmp, relative)
		if err = os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			return "", err
		}
		if err = os.WriteFile(path, b, 0o600); err != nil {
			return "", err
		}
	}
	if err = writeJSON(filepath.Join(tmp, "SOURCE.json"), map[string]any{"repository": "https://github.com/nicodes/komizo", "revision": RuntimeIdentity(), "files": files}); err != nil {
		return "", err
	}
	if err = os.Rename(tmp, root); err != nil {
		if check := verifyRuntime(root, files); check != nil {
			return "", err
		}
	}
	return root, verifyRuntime(root, files)
}

func toolConfig(tools map[string]json.RawMessage) (string, error) {
	keys := make([]string, 0, len(tools))
	for k := range tools {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var result strings.Builder
	result.WriteString("# Generated by Komizo; edit komizo.json and run komizo lock.\n[tools]\n")
	for _, key := range keys {
		var value any
		if err := json.Unmarshal(tools[key], &value); err != nil {
			return "", err
		}
		rendered, err := tomlValue(value)
		if err != nil {
			return "", err
		}
		b, _ := json.Marshal(key)
		fmt.Fprintf(&result, "%s = %s\n", b, rendered)
	}
	return result.String(), nil
}

func tomlValue(v any) (string, error) {
	switch value := v.(type) {
	case string, bool, float64:
		b, err := json.Marshal(value)
		return string(b), err
	case map[string]any:
		keys := make([]string, 0, len(value))
		for k := range value {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		parts := make([]string, 0, len(keys))
		for _, k := range keys {
			b, err := tomlValue(value[k])
			if err != nil {
				return "", err
			}
			key, _ := json.Marshal(k)
			parts = append(parts, string(key)+" = "+b)
		}
		return "{" + strings.Join(parts, ", ") + "}", nil
	case []any:
		parts := make([]string, 0, len(value))
		for _, item := range value {
			b, err := tomlValue(item)
			if err != nil {
				return "", err
			}
			parts = append(parts, b)
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	default:
		return "", errors.New("unsupported tool configuration value")
	}
}

// Generated output never follows an existing directory link out of a checkout.
func projectDirectory(root string, parts ...string) error {
	path := root
	for _, part := range parts {
		path = filepath.Join(path, part)
		info, err := os.Lstat(path)
		if errors.Is(err, os.ErrNotExist) {
			if err = os.Mkdir(path, 0700); err != nil {
				return err
			}
			continue
		}
		if err != nil {
			return err
		}
		if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
			return errors.New("generated directory must be a regular checkout directory")
		}
	}
	return nil
}
